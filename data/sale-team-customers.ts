function normalize(value: string) {
  return value.toLocaleLowerCase().replace(/\s+/g, " ").trim();
}

const assignmentMap = new Map(
  SALE_TEAM_CUSTOMERS.map((item) => [`${normalize(item.customerName)}|||${normalize(item.township)}`, item]),
);
const assignmentByName = new Map<string, SaleTeamCustomerAssignment>();
const duplicateNames = new Set<string>();
for (const item of SALE_TEAM_CUSTOMERS) {
  const key = normalize(item.customerName);
  if (assignmentByName.has(key)) duplicateNames.add(key);
  else assignmentByName.set(key, item);
}
for (const key of duplicateNames) assignmentByName.delete(key);

const salespersonAliases: Record<string, string> = {
  akz: "Aung Kyaw Zaw",
  zmml: "Zin Mg Mg Lin",
  mm: "Myo Min",
  hlks: "Htin Lin Kyaw Swar",
  hlk: "Htin Lin Kyaw Swar",
  ztk: "Zaw Tun Kyaw",
  admin: "Admin",
};

export function canonicalSalesperson(value: string) {
  return salespersonAliases[normalize(value)] || value.trim();
}

export function teamForSalesperson(value: string): SaleTeam | "" {
  const salesperson = canonicalSalesperson(value);
  if (["Zin Mg Mg Lin", "Myo Min", "Htin Lin Kyaw Swar", "Aung Kyaw Zaw"].includes(salesperson)) return "A";
  if (["Admin", "Zaw Tun Kyaw"].includes(salesperson)) return "B";
  return "";
}

export function getListedSaleTeamAssignment(customerName: string, township: string) {
  return assignmentMap.get(`${normalize(customerName)}|||${normalize(township)}`) || assignmentByName.get(normalize(customerName)) || null;
}

export function getSaleTeamAssignment(customerName: string, township: string, fallbackSalesperson = "") {
  const listed = getListedSaleTeamAssignment(customerName, township);
  if (listed) return listed;
  const salesperson = canonicalSalesperson(fallbackSalesperson);
  const team = teamForSalesperson(salesperson);
  return team ? { team, salesperson, customerName, township } : null;
}

